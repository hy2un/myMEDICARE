import streamlit as st

from drug_data_tools import (
    load_data,
    filter_drugs,
)


st.title("🗂️ 약 종류")

st.caption(
    "전체 의약품을 확인하거나 "
    "약 종류를 선택해 해당 제품만 볼 수 있습니다."
)


# =========================================================
# 데이터 불러오기
# =========================================================
drug_data, _ = load_data()


# =========================================================
# 약 종류 목록 만들기
# =========================================================
categories = sorted(
    drug_data[
        "카테고리"
    ]
    .dropna()
    .unique()
    .tolist()
)


# 전체 보기 항목 추가
category_options = [
    "전체 보기"
] + categories


# =========================================================
# 약 종류 선택
# =========================================================
selected_category = st.selectbox(
    "약 종류 선택",
    category_options,
)


# =========================================================
# 전체 보기
# =========================================================
if selected_category == "전체 보기":

    result = drug_data.copy()

    st.subheader("전체 의약품")

    st.write(
        f"총 **{len(result)}개 제품**이 있습니다."
    )


# =========================================================
# 특정 종류 보기
# =========================================================
else:

    result = filter_drugs(
        drug_data,
        selected_category,
    )

    st.subheader(
        f"{selected_category}"
    )

    st.write(
        f"총 **{len(result)}개 제품**이 있습니다."
    )


# =========================================================
# 결과 표시
# =========================================================
st.dataframe(
    result[
        [
            "제품명",
            "제조사",
            "카테고리",
            "성분",
        ]
    ],
    use_container_width=True,
    hide_index=True,
)
